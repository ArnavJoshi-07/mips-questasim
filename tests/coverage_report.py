#!/usr/bin/env python3
"""Merge the per-program coverage counts of tests/tb_suite.v into a report.

    python3 tests/coverage_report.py tests/build/cov <program> [...] > docs/coverage.md

Each <dir>/<program>.txt holds "name count" lines written by tb_suite
(+COV=...): the coverage bins, then the pipeline counters ("count.*").
`make coverage` runs the suite and this script.
"""
import sys
from pathlib import Path

# What each bin means. Sampled once per pipeline cycle; see sample_coverage
# in tests/tb_suite.v for the exact condition.
DESCRIPTION = {
    "instr.add": "add in EX",
    "instr.sub": "sub in EX",
    "instr.and": "and in EX",
    "instr.or": "or in EX",
    "instr.slt": "slt in EX",
    "instr.addi": "addi in EX",
    "instr.lw": "lw in EX",
    "instr.sw": "sw in EX",
    "instr.beq": "beq in EX",
    "instr.j": "j in EX",
    "instr.nop": "a nop from the program in EX (not a bubble)",
    "alu.result_zero": "ALU result is 0",
    "alu.result_negative": "ALU result has bit 31 set",
    "alu.overflow_wraps": "add, addi or sub overflows and wraps (no trap)",
    "alu.slt_true": "slt gives 1",
    "alu.slt_false": "slt gives 0",
    "alu.slt_overflow": "slt where a - b overflows (sign must be corrected)",
    "fwd.a_from_ex_mem": "operand A (rs) forwarded from EX/MEM",
    "fwd.a_from_mem_wb": "operand A (rs) forwarded from MEM/WB",
    "fwd.b_from_ex_mem": "operand B (rt, as a source) forwarded from EX/MEM",
    "fwd.b_from_mem_wb": "operand B (rt, as a source) forwarded from MEM/WB",
    "fwd.both_operands": "A and B both forwarded in the same cycle",
    "fwd.double_hazard_a": "EX/MEM and MEM/WB both write rs: EX/MEM wins",
    "fwd.double_hazard_b": "EX/MEM and MEM/WB both write rt: EX/MEM wins",
    "fwd.store_data": "sw store data (rt) forwarded",
    "fwd.branch_operand": "beq operand forwarded",
    "fwd.load_result": "a loaded value forwarded from MEM/WB",
    "fwd.zero_not_forwarded": "EX/MEM writes $zero while EX reads $zero: not forwarded",
    "fwd.regfile_write_then_read": "WB writes a register ID reads in the same cycle",
    "stall.on_rs": "load-use stall on the consumer's rs",
    "stall.on_rt": "load-use stall on the consumer's rt",
    "stall.alu_consumer": "load-use stall on an R-type or addi",
    "stall.lw_consumer": "load-use stall on a lw (address from a load)",
    "stall.sw_consumer": "load-use stall on a sw",
    "stall.beq_consumer": "load-use stall on a beq",
    "stall.j_held": "stall with a j in ID: the j waits instead of flushing",
    "stall.lw_zero_no_stall": "lw to $zero, then a reader of $zero: no stall",
    "flush.beq_taken": "taken beq flushes IF/ID and ID/EX",
    "flush.beq_not_taken": "not-taken beq, nothing flushed",
    "flush.j": "j flushes IF/ID",
    "flush.beq_squashes_j": "taken beq in EX and a j in ID: the beq wins",
    "flush.back_to_back_beq": "taken beq with another beq right behind it",
    "mem.negative_offset": "lw or sw with a negative offset",
    "mem.load_after_store": "lw right after a sw to the same word",
    "mem.address_wraps": "lw or sw above 1 KB (wraps to the bottom of dmem)",
    "reg.write_to_zero": "an instruction with $zero as destination reaches WB",
}

AREAS = [("instr", "Instructions"), ("alu", "ALU"), ("fwd", "Forwarding"),
         ("stall", "Load-use stalls"), ("flush", "Branches, jumps and flushes"),
         ("mem", "Data memory"), ("reg", "Register file")]


def read(path):
    data = {}
    for line in path.read_text().splitlines():
        name, value = line.split()
        data[name] = int(value)
    return data


def main(argv):
    if len(argv) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    covdir, programs = Path(argv[0]), argv[1:]
    runs = {p: read(covdir / f"{p}.txt") for p in programs}
    bins = [b for b in next(iter(runs.values())) if not b.startswith("count.")]
    hit = {b: [p for p in programs if runs[p][b]] for b in bins}
    covered = sum(1 for b in bins if hit[b])

    out = []
    w = out.append
    w("# Functional Coverage Report\n")
    w("Generated by `make coverage`: every program in `programs/` runs on the "
      "pipeline (`mips_top`) and the single-cycle core (`mips_single`) in "
      "`tests/tb_suite.v`, which samples the bins below once per pipeline cycle. "
      "Do not edit by hand.\n")
    w(f"**{covered} of {len(bins)} bins covered ({100 * covered / len(bins):.0f}%)** "
      f"over {len(programs)} programs.\n")

    missing = [b for b in bins if not hit[b]]
    if missing:
        w("Not covered: " + ", ".join(f"`{b}`" for b in missing) + "\n")

    w("## Programs\n")
    w("Every program passed: its registers and data memory match the "
      "single-cycle core and its `# expect` lines. CPI counts the cycles up to "
      "the halt reaching WB, over the instructions retired (nops excluded).\n")
    w("| Program | Cycles | Retired | CPI | Single-cycle | Stalls | beq flushes "
      "| j flushes | A←EX/MEM | A←MEM/WB | B←EX/MEM | B←MEM/WB |")
    w("|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|")
    for p in programs:
        r = runs[p]
        cyc, ret = r["count.cycles"], r["count.retired"]
        cpi = cyc * 100 // ret          # truncated, as tb_suite prints it
        w(f"| `{p}` | {cyc} | {ret} | {cpi // 100}.{cpi % 100:02d} | {r['count.single_cycle_cycles']} "
          f"| {r['count.stalls']} | {r['count.beq_flushes']} | {r['count.j_flushes']} "
          f"| {r['count.fwd_a_mem']} | {r['count.fwd_a_wb']} "
          f"| {r['count.fwd_b_mem']} | {r['count.fwd_b_wb']} |")
    w("")

    w("## Bins\n")
    w("*Hits* is the number of cycles the bin's condition held, summed over all "
      "programs.\n")
    for prefix, title in AREAS:
        area = [b for b in bins if b.split(".")[0] == prefix]
        if not area:
            continue
        n = sum(1 for b in area if hit[b])
        w(f"### {title} ({n}/{len(area)})\n")
        w("| Bin | Meaning | Hits | Hit by |")
        w("|---|---|--:|---|")
        for b in area:
            total = sum(runs[p][b] for p in programs)
            by = ", ".join(hit[b]) if hit[b] else "**not covered**"
            w(f"| `{b}` | {DESCRIPTION.get(b, '')} | {total} | {by} |")
        w("")

    w("## Code coverage\n")
    w("Statement, branch, condition, expression and toggle coverage of the RTL "
      "come from QuestaSim: `SIM=questa make coverage` writes one UCDB per "
      "program, merges them into `tests/build/merged.ucdb` and reports to "
      "`tests/build/code_coverage.txt` and `tests/build/coverage_html/`.")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
